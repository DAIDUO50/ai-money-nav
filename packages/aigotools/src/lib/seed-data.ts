export function getSeedFeaturedSites(size = 12): Site[] {
  return SEED_SITES.filter((s) => s.featured)
    .sort((a, b) => b.weight - a.weight)
    .slice(0, size);
}

export function getSeedLatestSites(size = 12): Site[] {
  return [...SEED_SITES]
    .sort((a, b) => b.updatedAt - a.updatedAt)
    .slice(0, size);
}

export function getSeedFeaturedCategories(): Category[] {
  return SEED_CATEGORIES.filter((c) => c.featured).sort(
    (a, b) => b.weight - a.weight,
  );
}

export function getSeedSiteByKey(siteKey: string): Site | undefined {
  return SEED_SITES.find((s) => s.siteKey === siteKey);
}


export function searchSeedSites({
  search,
  category,
  page,
  pricing = "all",
  rating = 0,
}: {
  search: string;
  category: string;
  page: number;
  pricing?: "all" | "free" | "paid";
  rating?: number;
}): { sites: Site[]; total: number } {
  const pageSize = 24;
  let filtered = SEED_SITES.filter((s) => s.state === SiteState.published);

  // Pricing filter
  if (pricing === "free") {
    filtered = filtered.filter((s) => s.pricingType?.includes("免费"));
  } else if (pricing === "paid") {
    filtered = filtered.filter((s) => !s.pricingType?.includes("免费"));
  }

  // Rating filter (skip for seed data as it doesn't have rating field)
  // TODO: Add rating field to seed data if needed

  if (category) {
    filtered = filtered.filter((s) =>
      s.categories.some((c) => c.includes(category)),
    );
  }

  if (search) {
    const q = search.toLowerCase();
    filtered = filtered.filter(
      (s) =>
        s.name.toLowerCase().includes(q) ||
        s.description.toLowerCase().includes(q) ||
        s.categories.some((c) => c.toLowerCase().includes(q)) ||
        s.searchSuggestWords.some((w) => w.toLowerCase().includes(q)),
    );
  }

  const total = filtered.length;
  const sites = filtered.slice((page - 1) * pageSize, page * pageSize);

  return { sites, total };
}
